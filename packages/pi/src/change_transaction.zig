//! Crash-consistent workspace transaction for one proven source change set.
//!
//! POSIX cannot make several path renames instantaneously visible to processes
//! that ignore this workspace lock. Cooperating zttp writers are serialized,
//! and the journal guarantees recovery to one complete final state.

const std = @import("std");
const zts = @import("zts");
const TextBuffer = @import("text_buffer.zig").TextBuffer;
const change_set = @import("change_set.zig");
const workspace_snapshot = @import("workspace_snapshot.zig");
const aggregate_proof = @import("aggregate_proof.zig");
const common = @import("tools/common.zig");

const journal_schema_version: u32 = 1;

pub const FaultPoint = union(enum) {
    none,
    before_manifest_write,
    before_image_write: usize,
    before_receipt_write,
    after_prepared,
    before_stage_write: usize,
    after_applying,
    before_rename: usize,
    after_rename: usize,
    after_committed,
};

pub const CommitOptions = struct {
    fault: FaultPoint = .none,
    /// Exact aggregate UI/session receipt serialized before the first rename.
    /// Tests and lower-level callers may omit it and receive the compact
    /// transaction receipt generated by this module.
    receipt_json: ?[]const u8 = null,
};

pub const RecoveryFaultPoint = union(enum) {
    none,
    after_aborted_marker,
    before_transaction_directory_sync,
    before_source_file_sync: usize,
    before_source_directory_sync: usize,
    after_source_write: usize,
    after_candidate_verification,
    after_committed_marker,
    after_receipted_marker,
};

pub const RecoveryOptions = struct {
    fault: RecoveryFaultPoint = .none,
};

pub const CommitReceipt = struct {
    transaction_id: [64]u8,
    receipt_path: []u8,

    pub fn deinit(self: *CommitReceipt, allocator: std.mem.Allocator) void {
        allocator.free(self.receipt_path);
        self.* = undefined;
    }
};

/// A committed workspace receipt that has not yet been durably acknowledged by
/// its owning session journal. The transaction directory remains authoritative
/// until `markReceiptedLocked` succeeds.
pub const PendingReceipt = struct {
    transaction_id: [64]u8,
    json: []u8,

    pub fn deinit(self: *PendingReceipt, allocator: std.mem.Allocator) void {
        allocator.free(self.json);
        self.* = undefined;
    }
};

pub const WorkspaceLock = struct {
    allocator: std.mem.Allocator,
    fd: std.c.fd_t,
    path: []u8,

    pub fn acquire(allocator: std.mem.Allocator, workspace_root: []const u8) !WorkspaceLock {
        const canonical_workspace = try common.resolveInsideWorkspace(allocator, workspace_root, ".");
        defer allocator.free(canonical_workspace);
        const state_dir = try std.fs.path.resolve(allocator, &.{ canonical_workspace, ".zttp" });
        defer allocator.free(state_dir);
        var io_backend = std.Io.Threaded.init(allocator, .{ .environ = .empty });
        defer io_backend.deinit();
        try std.Io.Dir.createDirPath(std.Io.Dir.cwd(), io_backend.io(), state_dir);
        try syncDirectory(allocator, state_dir);

        const path = try std.fs.path.resolve(allocator, &.{ state_dir, "change-set.lock" });
        errdefer allocator.free(path);
        const path_z = try allocator.dupeZ(u8, path);
        defer allocator.free(path_z);
        const fd = try std.posix.openatZ(
            std.posix.AT.FDCWD,
            path_z,
            .{ .ACCMODE = .WRONLY, .CREAT = true },
            0o600,
        );
        errdefer std.Io.Threaded.closeFd(fd);
        try lockExclusiveNonBlocking(fd);
        return .{ .allocator = allocator, .fd = fd, .path = path };
    }

    pub fn deinit(self: *WorkspaceLock) void {
        _ = std.c.flock(self.fd, std.posix.LOCK.UN);
        std.Io.Threaded.closeFd(self.fd);
        self.allocator.free(self.path);
        self.* = undefined;
    }
};

const ManifestChange = struct {
    path: []const u8,
    baseline_state: []const u8,
    baseline_sha256: []const u8,
    candidate_sha256: []const u8,
};

const Manifest = struct {
    schema_version: u32,
    proof_id: []const u8,
    workspace_root: []const u8,
    changes: []const ManifestChange,
};

pub fn commitLocked(
    allocator: std.mem.Allocator,
    lock: *const WorkspaceLock,
    prepared: *const change_set.PreparedChangeSet,
    snapshot: *const workspace_snapshot.Snapshot,
    proof: *const aggregate_proof.AggregateProof,
    options: CommitOptions,
) !CommitReceipt {
    _ = lock;
    try snapshot.recheck(allocator);

    const transaction_dir = try transactionPath(allocator, prepared.workspace_root, &proof.proof_id);
    defer allocator.free(transaction_dir);
    if (try pathExists(allocator, transaction_dir)) return error.TransactionAlreadyExists;
    const images_dir = try std.fs.path.resolve(allocator, &.{ transaction_dir, "images" });
    defer allocator.free(images_dir);
    var io_backend = std.Io.Threaded.init(allocator, .{ .environ = .empty });
    defer io_backend.deinit();
    const io = io_backend.io();
    try std.Io.Dir.createDirPath(std.Io.Dir.cwd(), io, images_dir);

    if (options.fault == .before_manifest_write) return error.InjectedTransactionFailure;
    try writeManifest(allocator, transaction_dir, prepared, proof);
    try writeImages(allocator, transaction_dir, prepared, options.fault);
    if (options.fault == .before_receipt_write) return error.InjectedTransactionFailure;
    if (options.receipt_json) |receipt_json|
        try writeProvidedReceipt(allocator, transaction_dir, receipt_json, &proof.proof_id)
    else
        try writeReceipt(allocator, transaction_dir, prepared, proof);
    try writeMarker(allocator, transaction_dir, "prepared");
    try syncDirectory(allocator, transaction_dir);
    if (options.fault == .after_prepared) return error.InjectedTransactionFailure;

    try snapshot.recheck(allocator);
    const stages = try stageCandidates(allocator, prepared, &proof.proof_id, options.fault);
    defer {
        for (stages) |stage| {
            deleteFileIfPresent(allocator, stage) catch {};
            allocator.free(stage);
        }
        allocator.free(stages);
    }
    try snapshot.recheck(allocator);
    try writeMarker(allocator, transaction_dir, "applying");
    if (options.fault == .after_applying) return error.InjectedTransactionFailure;

    for (prepared.changes, stages, 0..) |change, stage, index| {
        switch (options.fault) {
            .before_rename => |fault_index| if (fault_index == index) return error.RenameFailure,
            else => {},
        }
        try renameAndSync(allocator, stage, change.resolved_path);
        try writeProgressMarker(allocator, transaction_dir, index);
        switch (options.fault) {
            .after_rename => |fault_index| if (fault_index == index) return error.InjectedTransactionFailure,
            else => {},
        }
    }
    try verifyCandidates(allocator, prepared);
    try writeMarker(allocator, transaction_dir, "committed");
    if (options.fault == .after_committed) return error.InjectedTransactionFailure;
    return .{
        .transaction_id = proof.proof_id,
        .receipt_path = try std.fs.path.resolve(allocator, &.{ transaction_dir, "receipt.json" }),
    };
}

/// Return committed receipts whose session acknowledgement is still missing.
/// Callers must first run `recoverAllLocked`: this scanner deliberately refuses
/// an incomplete transaction instead of guessing whether its source writes are
/// authoritative. Results are sorted by transaction id for deterministic
/// reconstruction.
pub fn pendingReceiptsLocked(
    allocator: std.mem.Allocator,
    lock: *const WorkspaceLock,
    workspace_root: []const u8,
) ![]PendingReceipt {
    _ = lock;
    const canonical_workspace = try common.resolveInsideWorkspace(allocator, workspace_root, ".");
    defer allocator.free(canonical_workspace);
    const root = try std.fs.path.resolve(allocator, &.{ canonical_workspace, ".zttp", "change-sets" });
    defer allocator.free(root);
    var io_backend = std.Io.Threaded.init(allocator, .{ .environ = .empty });
    defer io_backend.deinit();
    const io = io_backend.io();
    var dir = std.Io.Dir.openDirAbsolute(io, root, .{ .iterate = true, .follow_symlinks = false }) catch |err| switch (err) {
        error.FileNotFound => return allocator.alloc(PendingReceipt, 0),
        else => return err,
    };
    defer dir.close(io);

    var transaction_ids: std.ArrayList([64]u8) = .empty;
    defer transaction_ids.deinit(allocator);
    var iterator = dir.iterate();
    while (try iterator.next(io)) |entry| {
        if (entry.kind != .directory or !isCanonicalProofId(entry.name)) return error.CorruptTransactionDirectory;
        const transaction_dir = try std.fs.path.resolve(allocator, &.{ root, entry.name });
        defer allocator.free(transaction_dir);
        if (!try markerPresent(allocator, transaction_dir, "prepared") or
            !try markerPresent(allocator, transaction_dir, "committed"))
        {
            return error.IncompleteTransactionRecovery;
        }
        if (try markerPresent(allocator, transaction_dir, "receipted")) continue;
        if (transaction_ids.items.len >= 1024) return error.TooManyPendingReceipts;
        var id: [64]u8 = undefined;
        @memcpy(&id, entry.name);
        try transaction_ids.append(allocator, id);
    }
    std.mem.sort([64]u8, transaction_ids.items, {}, struct {
        fn lessThan(_: void, left: [64]u8, right: [64]u8) bool {
            return std.mem.order(u8, &left, &right) == .lt;
        }
    }.lessThan);

    const receipts = try allocator.alloc(PendingReceipt, transaction_ids.items.len);
    var initialized: usize = 0;
    errdefer {
        for (receipts[0..initialized]) |*receipt| receipt.deinit(allocator);
        allocator.free(receipts);
    }
    for (transaction_ids.items, 0..) |id, index| {
        const transaction_dir = try std.fs.path.resolve(allocator, &.{ root, id[0..] });
        defer allocator.free(transaction_dir);
        try validateReceipt(allocator, transaction_dir, &id);
        const path = try std.fs.path.resolve(allocator, &.{ transaction_dir, "receipt.json" });
        defer allocator.free(path);
        receipts[index] = .{
            .transaction_id = id,
            .json = try readVerifiedFile(allocator, path, 64 * 1024 * 1024),
        };
        initialized += 1;
    }
    return receipts;
}

/// Durably records that the exact committed receipt is now present in its
/// owning persistence surface. This is idempotent and never removes the
/// workspace receipt.
pub fn markReceiptedLocked(
    allocator: std.mem.Allocator,
    lock: *const WorkspaceLock,
    workspace_root: []const u8,
    transaction_id: *const [64]u8,
) !void {
    return markReceiptedLockedWithOptions(
        allocator,
        lock,
        workspace_root,
        transaction_id,
        .{},
    );
}

/// Test-capable acknowledgement entry point. Default options are identical to
/// `markReceiptedLocked`; injected failures occur at named durable-effect
/// boundaries.
pub fn markReceiptedLockedWithOptions(
    allocator: std.mem.Allocator,
    lock: *const WorkspaceLock,
    workspace_root: []const u8,
    transaction_id: *const [64]u8,
    options: RecoveryOptions,
) !void {
    _ = lock;
    if (!isCanonicalProofId(transaction_id)) return error.InvalidTransactionId;
    const transaction_dir = try transactionPath(allocator, workspace_root, transaction_id);
    defer allocator.free(transaction_dir);
    if (!try markerPresent(allocator, transaction_dir, "prepared") or
        !try markerPresent(allocator, transaction_dir, "committed"))
    {
        return error.TransactionNotCommitted;
    }
    try validateReceipt(allocator, transaction_dir, transaction_id);
    if (!try markerPresent(allocator, transaction_dir, "receipted")) {
        try writeMarker(allocator, transaction_dir, "receipted");
        if (options.fault == .after_receipted_marker) return error.InjectedTransactionFailure;
    }
}

pub fn recoverAllLocked(
    allocator: std.mem.Allocator,
    lock: *const WorkspaceLock,
    workspace_root: []const u8,
) !usize {
    return recoverAllLockedWithOptions(allocator, lock, workspace_root, .{});
}

/// Test-capable recovery entry point. Default options are identical to
/// `recoverAllLocked`; injected failures occur at named durable-effect
/// boundaries.
pub fn recoverAllLockedWithOptions(
    allocator: std.mem.Allocator,
    lock: *const WorkspaceLock,
    workspace_root: []const u8,
    options: RecoveryOptions,
) !usize {
    _ = lock;
    const canonical_workspace = try common.resolveInsideWorkspace(allocator, workspace_root, ".");
    defer allocator.free(canonical_workspace);
    const root = try std.fs.path.resolve(allocator, &.{ canonical_workspace, ".zttp", "change-sets" });
    defer allocator.free(root);
    var io_backend = std.Io.Threaded.init(allocator, .{ .environ = .empty });
    defer io_backend.deinit();
    const io = io_backend.io();
    var dir = std.Io.Dir.openDirAbsolute(io, root, .{ .iterate = true, .follow_symlinks = false }) catch |err| switch (err) {
        error.FileNotFound => return 0,
        else => return err,
    };
    defer dir.close(io);
    var recovered: usize = 0;
    var iterator = dir.iterate();
    while (try iterator.next(io)) |entry| {
        if (entry.kind != .directory or !isCanonicalProofId(entry.name)) return error.CorruptTransactionDirectory;
        const transaction_dir = try std.fs.path.resolve(allocator, &.{ root, entry.name });
        defer allocator.free(transaction_dir);
        if (try recoverOne(allocator, transaction_dir, options)) recovered += 1;
    }
    return recovered;
}

const PreparationState = enum { unprepared, prepared };

const RecoveryPhase = enum {
    unprepared,
    aborted,
    committed,
    prepared,
    applying,
};

const PreparedRecoveryPhase = enum { aborted, committed, prepared, applying };

const TargetObservation = struct {
    current: [32]u8,
    baseline: [32]u8,
    candidate: [32]u8,
};

const TargetAction = enum { keep_candidate, write_candidate };

const ApplyingPlan = struct {
    /// Borrows storage owned by the parsed manifest in `recoverOne`.
    manifest: Manifest,
    /// Owned by this plan.
    actions: []TargetAction,
};

const RecoveryPlan = union(RecoveryPhase) {
    unprepared: void,
    aborted: void,
    committed: void,
    prepared: void,
    applying: ApplyingPlan,

    fn deinit(self: *RecoveryPlan, allocator: std.mem.Allocator) void {
        switch (self.*) {
            .applying => |applying| allocator.free(applying.actions),
            .unprepared, .aborted, .committed, .prepared => {},
        }
        self.* = undefined;
    }
};

const ApplyingPlanner = struct {
    /// Borrows storage owned by the parsed manifest in `recoverOne`.
    manifest: Manifest,
    /// Owned until `finish` transfers it to a `RecoveryPlan`.
    actions: []TargetAction,
    next_index: usize,
};

const RecoveryPlanner = union(RecoveryPhase) {
    unprepared: void,
    aborted: void,
    committed: void,
    prepared: void,
    applying: ApplyingPlanner,

    fn observe(self: *RecoveryPlanner, observation: TargetObservation) !void {
        const applying = switch (self.*) {
            .applying => |*value| value,
            .unprepared, .aborted, .committed, .prepared => return error.RecoveryPhaseHasNoTargets,
        };
        if (applying.next_index >= applying.actions.len) return error.TooManyRecoveryObservations;
        const action: TargetAction = if (std.mem.eql(u8, &observation.current, &observation.candidate))
            .keep_candidate
        else if (std.mem.eql(u8, &observation.current, &observation.baseline))
            .write_candidate
        else
            return error.WorkspaceRecoveryConflict;
        applying.actions[applying.next_index] = action;
        applying.next_index += 1;
    }

    fn finish(self: *RecoveryPlanner) !RecoveryPlan {
        const plan: RecoveryPlan = switch (self.*) {
            .unprepared => .{ .unprepared = {} },
            .aborted => .{ .aborted = {} },
            .committed => .{ .committed = {} },
            .prepared => .{ .prepared = {} },
            .applying => |applying| blk: {
                if (applying.actions.len != applying.manifest.changes.len or
                    applying.next_index != applying.actions.len)
                {
                    return error.IncompleteRecoveryPlan;
                }
                break :blk .{ .applying = .{
                    .manifest = applying.manifest,
                    .actions = applying.actions,
                } };
            },
        };
        self.* = undefined;
        return plan;
    }

    fn deinit(self: *RecoveryPlanner, allocator: std.mem.Allocator) void {
        switch (self.*) {
            .applying => |applying| allocator.free(applying.actions),
            .unprepared, .aborted, .committed, .prepared => {},
        }
        self.* = undefined;
    }
};

fn observePreparation(allocator: std.mem.Allocator, transaction_dir: []const u8) !PreparationState {
    if (try markerPresent(allocator, transaction_dir, "prepared")) return .prepared;
    if (try markerPresent(allocator, transaction_dir, "applying") or
        try markerPresent(allocator, transaction_dir, "committed") or
        try markerPresent(allocator, transaction_dir, "receipted"))
    {
        return error.CorruptTransactionJournal;
    }
    return .unprepared;
}

fn observePreparedPhase(allocator: std.mem.Allocator, transaction_dir: []const u8) !PreparedRecoveryPhase {
    if (try markerPresent(allocator, transaction_dir, "aborted")) return .aborted;
    if (try markerPresent(allocator, transaction_dir, "committed")) return .committed;
    if (!try markerPresent(allocator, transaction_dir, "applying")) return .prepared;
    return .applying;
}

fn recoverOne(
    allocator: std.mem.Allocator,
    transaction_dir: []const u8,
    options: RecoveryOptions,
) !bool {
    if (try observePreparation(allocator, transaction_dir) == .unprepared) {
        var planner: RecoveryPlanner = .{ .unprepared = {} };
        var plan = try planner.finish();
        defer plan.deinit(allocator);
        return executeRecoveryPlan(allocator, transaction_dir, &plan, options);
    }

    var parsed = try loadManifest(allocator, transaction_dir);
    defer parsed.deinit();
    const manifest = parsed.value;
    try validateManifestAndImages(allocator, transaction_dir, manifest);
    const phase = try observePreparedPhase(allocator, transaction_dir);
    if (phase == .committed) {
        try validateReceipt(allocator, transaction_dir, manifest.proof_id);
    }

    var planner: RecoveryPlanner = switch (phase) {
        .aborted => .{ .aborted = {} },
        .committed => .{ .committed = {} },
        .prepared => .{ .prepared = {} },
        .applying => blk: {
            const actions = try allocator.alloc(TargetAction, manifest.changes.len);
            break :blk .{ .applying = .{
                .manifest = manifest,
                .actions = actions,
                .next_index = 0,
            } };
        },
    };
    var planner_owned = true;
    defer if (planner_owned) planner.deinit(allocator);

    if (phase == .applying) {
        for (manifest.changes) |change| {
            const current = try readStateDigest(allocator, change.path);
            const candidate = parseDigest(change.candidate_sha256) orelse return error.CorruptTransactionJournal;
            const baseline = parseDigest(change.baseline_sha256) orelse return error.CorruptTransactionJournal;
            try planner.observe(.{
                .current = current,
                .baseline = baseline,
                .candidate = candidate,
            });
        }
    }

    var plan = try planner.finish();
    planner_owned = false;
    defer plan.deinit(allocator);
    return executeRecoveryPlan(allocator, transaction_dir, &plan, options);
}

fn executeRecoveryPlan(
    allocator: std.mem.Allocator,
    transaction_dir: []const u8,
    plan: *const RecoveryPlan,
    options: RecoveryOptions,
) !bool {
    switch (plan.*) {
        .unprepared, .aborted => {
            try deleteTransactionDirectory(allocator, transaction_dir, options);
            return true;
        },
        .committed => return false,
        .prepared => {
            try writeMarker(allocator, transaction_dir, "aborted");
            if (options.fault == .after_aborted_marker) return error.InjectedTransactionFailure;
            try deleteTransactionDirectory(allocator, transaction_dir, options);
            return true;
        },
        .applying => |applying| {
            if (applying.actions.len != applying.manifest.changes.len)
                return error.IncompleteRecoveryPlan;
            for (applying.manifest.changes, applying.actions, 0..) |change, action, index| {
                switch (action) {
                    .keep_candidate => continue,
                    .write_candidate => {
                        const after_path = try imagePath(allocator, transaction_dir, index, "after");
                        defer allocator.free(after_path);
                        const after = try zts.file_io.readFile(allocator, after_path, change_set.max_file_bytes);
                        defer allocator.free(after);
                        try durableRecoveryWrite(allocator, change.path, after, index, options);
                        switch (options.fault) {
                            .after_source_write => |fault_index| if (fault_index == index)
                                return error.InjectedTransactionFailure,
                            else => {},
                        }
                    },
                }
            }
            try verifyManifestCandidates(allocator, applying.manifest);
            if (options.fault == .after_candidate_verification) return error.InjectedTransactionFailure;
            try writeMarker(allocator, transaction_dir, "committed");
            if (options.fault == .after_committed_marker) return error.InjectedTransactionFailure;
            return true;
        },
    }
}

fn durableRecoveryWrite(
    allocator: std.mem.Allocator,
    path: []const u8,
    bytes: []const u8,
    index: usize,
    options: RecoveryOptions,
) !void {
    const parent = std.fs.path.dirname(path) orelse return error.InvalidJournalPath;
    var io_backend = std.Io.Threaded.init(allocator, .{ .environ = .empty });
    defer io_backend.deinit();
    try std.Io.Dir.createDirPath(std.Io.Dir.cwd(), io_backend.io(), parent);
    try zts.file_io.writeFile(allocator, path, bytes);
    switch (options.fault) {
        .before_source_file_sync => |fault_index| if (fault_index == index)
            return error.SyncFailure,
        else => {},
    }
    try syncFile(allocator, path);
    switch (options.fault) {
        .before_source_directory_sync => |fault_index| if (fault_index == index)
            return error.DirectorySyncFailure,
        else => {},
    }
    try syncDirectory(allocator, parent);
}

fn writeManifest(
    allocator: std.mem.Allocator,
    transaction_dir: []const u8,
    prepared: *const change_set.PreparedChangeSet,
    proof: *const aggregate_proof.AggregateProof,
) !void {
    const changes = try allocator.alloc(ManifestChange, prepared.changes.len);
    defer allocator.free(changes);
    const digest_strings = try allocator.alloc([64]u8, prepared.changes.len * 2);
    defer allocator.free(digest_strings);
    for (prepared.changes, 0..) |change, index| {
        const candidate_digest = change_set.digestBaseline(change.candidate);
        digest_strings[index * 2] = std.fmt.bytesToHex(change.baseline_sha256, .lower);
        digest_strings[index * 2 + 1] = std.fmt.bytesToHex(candidate_digest, .lower);
        changes[index] = .{
            .path = change.resolved_path,
            .baseline_state = if (change.baseline == .absent) "absent" else "present",
            .baseline_sha256 = &digest_strings[index * 2],
            .candidate_sha256 = &digest_strings[index * 2 + 1],
        };
    }
    var buffer = TextBuffer.init(allocator);
    defer buffer.deinit();
    try std.json.Stringify.value(Manifest{
        .schema_version = journal_schema_version,
        .proof_id = proof.proof_id[0..],
        .workspace_root = prepared.workspace_root,
        .changes = changes,
    }, .{}, buffer.writer());
    const path = try std.fs.path.resolve(allocator, &.{ transaction_dir, "manifest.json" });
    defer allocator.free(path);
    try durableWriteWithDigest(allocator, path, buffer.written());
}

fn writeImages(
    allocator: std.mem.Allocator,
    transaction_dir: []const u8,
    prepared: *const change_set.PreparedChangeSet,
    fault: FaultPoint,
) !void {
    for (prepared.changes, 0..) |change, index| {
        switch (fault) {
            .before_image_write => |fault_index| if (fault_index == index)
                return error.InjectedTransactionFailure,
            else => {},
        }
        if (change.baseline.bytes()) |before| {
            const before_path = try imagePath(allocator, transaction_dir, index, "before");
            defer allocator.free(before_path);
            try durableWrite(allocator, before_path, before);
        }
        const after_path = try imagePath(allocator, transaction_dir, index, "after");
        defer allocator.free(after_path);
        try durableWrite(allocator, after_path, change.candidate);
    }
}

fn writeReceipt(
    allocator: std.mem.Allocator,
    transaction_dir: []const u8,
    prepared: *const change_set.PreparedChangeSet,
    proof: *const aggregate_proof.AggregateProof,
) !void {
    var buffer = TextBuffer.init(allocator);
    defer buffer.deinit();
    const writer = buffer.writer();
    try writer.writeAll("{\"schema_version\":1,\"kind\":\"verified_change_set\",\"transaction_id\":");
    try std.json.Stringify.value(&proof.proof_id, .{}, writer);
    try writer.writeAll(",\"policy_hash\":");
    try std.json.Stringify.value(&proof.policy_hash, .{}, writer);
    try writer.writeAll(",\"read_set_digest\":");
    try std.json.Stringify.value(&proof.read_set_digest, .{}, writer);
    try writer.writeAll(",\"system_proven\":");
    try writer.writeAll(if (proof.system_proven) "true" else "false");
    try writer.writeAll(",\"changes\":[");
    for (prepared.changes, 0..) |change, index| {
        if (index > 0) try writer.writeByte(',');
        var candidate_digest: [32]u8 = undefined;
        std.crypto.hash.sha2.Sha256.hash(change.candidate, &candidate_digest, .{});
        const candidate_hex = std.fmt.bytesToHex(candidate_digest, .lower);
        try writer.writeAll("{\"file\":");
        try std.json.Stringify.value(change.authored_path, .{}, writer);
        try writer.writeAll(",\"baseline_state\":");
        try std.json.Stringify.value(if (change.baseline == .absent) "absent" else "present", .{}, writer);
        try writer.writeAll(",\"baseline_sha256\":");
        const baseline_hex = std.fmt.bytesToHex(change.baseline_sha256, .lower);
        try std.json.Stringify.value(&baseline_hex, .{}, writer);
        try writer.writeAll(",\"candidate_sha256\":");
        try std.json.Stringify.value(&candidate_hex, .{}, writer);
        try writer.writeAll("}");
    }
    try writer.writeAll("]}");
    const path = try std.fs.path.resolve(allocator, &.{ transaction_dir, "receipt.json" });
    defer allocator.free(path);
    try durableWriteWithDigest(allocator, path, buffer.written());
}

fn writeProvidedReceipt(
