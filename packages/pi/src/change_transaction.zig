fn assertMarkerCase(mask: u8) !void {
    var tmp = testing.tmpDir(.{});
    defer tmp.cleanup();
    var fixture = try Fixture.init(testing.allocator, &tmp);
    defer fixture.deinit(testing.allocator);
    var lock = try WorkspaceLock.acquire(testing.allocator, fixture.root);
    defer lock.deinit();
    try testing.expectError(
        error.InjectedTransactionFailure,
        commitLocked(testing.allocator, &lock, &fixture.prepared, &fixture.snapshot, &fixture.proof, .{
            .fault = .after_prepared,
        }),
    );
    const transaction_dir = try transactionPath(testing.allocator, fixture.root, &fixture.proof.proof_id);
    defer testing.allocator.free(transaction_dir);
    try setMarker(testing.allocator, transaction_dir, "prepared", markerSet(mask, marker_prepared));
    try setMarker(testing.allocator, transaction_dir, "applying", markerSet(mask, marker_applying));
    try setMarker(testing.allocator, transaction_dir, "committed", markerSet(mask, marker_committed));
    try setMarker(testing.allocator, transaction_dir, "receipted", markerSet(mask, marker_receipted));
    try setMarker(testing.allocator, transaction_dir, "aborted", markerSet(mask, marker_aborted));

    switch (marker_case_outcomes[mask]) {
        .corrupt => {
            try testing.expectError(
                error.CorruptTransactionJournal,
                recoverAllLocked(testing.allocator, &lock, fixture.root),
            );
            try testing.expect(try pathExists(testing.allocator, transaction_dir));
            try expectFixtureCandidates(&fixture, false);
        },
        .delete_transaction => {
            try testing.expectEqual(@as(usize, 1), try recoverAllLocked(testing.allocator, &lock, fixture.root));
            try testing.expect(!try pathExists(testing.allocator, transaction_dir));
            try expectFixtureCandidates(&fixture, false);
            try expectPendingReceiptCount(&lock, fixture.root, 0);
        },
        .preserve_committed => {
            try testing.expectEqual(@as(usize, 0), try recoverAllLocked(testing.allocator, &lock, fixture.root));
            try testing.expect(try pathExists(testing.allocator, transaction_dir));
            try expectFixtureCandidates(&fixture, false);
            try expectPendingReceiptCount(
                &lock,
                fixture.root,
                if (markerSet(mask, marker_receipted)) 0 else 1,
            );
        },
        .roll_forward => {
            try testing.expectEqual(@as(usize, 1), try recoverAllLocked(testing.allocator, &lock, fixture.root));
            try testing.expect(try pathExists(testing.allocator, transaction_dir));
            try expectFixtureCandidates(&fixture, true);
            try expectPendingReceiptCount(
                &lock,
                fixture.root,
                if (markerSet(mask, marker_receipted)) 0 else 1,
            );
        },
    }
}

const TargetState = enum { baseline, candidate, third };

fn setTargetState(change: change_set.PreparedChange, state: TargetState) !void {
    switch (state) {
        .baseline => if (change.baseline.bytes()) |bytes|
            try durableWrite(testing.allocator, change.resolved_path, bytes)
        else
            try deleteFileIfPresent(testing.allocator, change.resolved_path),
        .candidate => try durableWrite(testing.allocator, change.resolved_path, change.candidate),
        .third => try durableWrite(testing.allocator, change.resolved_path, "third-state"),
    }
}

fn expectTargetState(change: change_set.PreparedChange, state: TargetState) !void {
    const expected: ?[]const u8 = switch (state) {
        .baseline => change.baseline.bytes(),
        .candidate => change.candidate,
        .third => "third-state",
    };
    if (expected) |bytes| {
        const current = try zts.file_io.readFile(testing.allocator, change.resolved_path, 64);
        defer testing.allocator.free(current);
        try testing.expectEqualStrings(bytes, current);
    } else {
        try testing.expect(!try pathExists(testing.allocator, change.resolved_path));
    }
}

fn assertTargetMatrixCase(mixed: bool, first: TargetState, second: TargetState) !void {
    var tmp = testing.tmpDir(.{});
    defer tmp.cleanup();
    var fixture = if (mixed)
        try Fixture.initMixed(testing.allocator, &tmp)
    else
        try Fixture.init(testing.allocator, &tmp);
    defer fixture.deinit(testing.allocator);
    var lock = try WorkspaceLock.acquire(testing.allocator, fixture.root);
    defer lock.deinit();
    try testing.expectError(
        error.InjectedTransactionFailure,
        commitLocked(testing.allocator, &lock, &fixture.prepared, &fixture.snapshot, &fixture.proof, .{
            .fault = .after_applying,
        }),
    );
    try setTargetState(fixture.prepared.changes[0], first);
    try setTargetState(fixture.prepared.changes[1], second);

    if (first == .third or second == .third) {
        try testing.expectError(
            error.WorkspaceRecoveryConflict,
            recoverAllLocked(testing.allocator, &lock, fixture.root),
        );
        try expectTargetState(fixture.prepared.changes[0], first);
        try expectTargetState(fixture.prepared.changes[1], second);
    } else {
        try testing.expectEqual(@as(usize, 1), try recoverAllLocked(testing.allocator, &lock, fixture.root));
        try expectTargetState(fixture.prepared.changes[0], .candidate);
        try expectTargetState(fixture.prepared.changes[1], .candidate);
    }
}

