fn expectPendingReceiptCount(lock: *const WorkspaceLock, root: []const u8, expected: usize) !void {
    const pending = try pendingReceiptsLocked(testing.allocator, lock, root);
    defer {
        for (pending) |*receipt| receipt.deinit(testing.allocator);
