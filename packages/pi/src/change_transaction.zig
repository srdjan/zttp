        defer allocator.free(root_z);
        const root = try allocator.dupe(u8, root_z);
        errdefer allocator.free(root);
        const tail = [_]@import("turn.zig").Change{.{ .file = "src/new.ts", .content = "new-file" }};
        var prepared = try change_set.prepare(allocator, root, .{
            .file = "src/a.ts",
            .content = "new-a",
            .additional = &tail,
        });
        errdefer prepared.deinit(allocator);
        var snapshot = try workspace_snapshot.Snapshot.capture(allocator, &prepared);
        errdefer snapshot.deinit(allocator);
        const roots = try allocator.alloc([]u8, 1);
        roots[0] = try allocator.dupe(u8, "src/a.ts");
        return .{
            .root = root,
            .prepared = prepared,
            .snapshot = snapshot,
            .proof = .{
                .proof_id = @splat('c'),
                .policy_hash = zts.policyHash(),
                .read_set_digest = @splat('d'),
                .proof_roots = roots,
                .diagnostics = try allocator.alloc(aggregate_proof.Diagnostic, 0),
                .system_proven = false,
            },
        };
    }

    fn deinit(self: *Fixture, allocator: std.mem.Allocator) void {
        self.proof.deinit(allocator);
        self.snapshot.deinit(allocator);
        self.prepared.deinit(allocator);
        allocator.free(self.root);
    }
};

const MarkerCaseOutcome = enum {
    corrupt,
    delete_transaction,
    preserve_committed,
    roll_forward,
};

const marker_prepared: u8 = 1 << 0;
const marker_applying: u8 = 1 << 1;
const marker_committed: u8 = 1 << 2;
const marker_receipted: u8 = 1 << 3;
const marker_aborted: u8 = 1 << 4;

fn markerSet(mask: u8, marker: u8) bool {
    return mask & marker != 0;
}

const marker_case_outcomes = [32]MarkerCaseOutcome{
    // 0b0_0000 through 0b0_0111.
    .delete_transaction,
    .delete_transaction,
    .corrupt,
    .roll_forward,
    .corrupt,
    .preserve_committed,
    .corrupt,
    .preserve_committed,
    // 0b0_1000 through 0b0_1111.
    .corrupt,
    .delete_transaction,
    .corrupt,
    .roll_forward,
    .corrupt,
    .preserve_committed,
    .corrupt,
    .preserve_committed,
    // 0b1_0000 through 0b1_0111. Aborted wins whenever prepared is present.
    .delete_transaction,
    .delete_transaction,
    .corrupt,
    .delete_transaction,
    .corrupt,
    .delete_transaction,
    .corrupt,
    .delete_transaction,
    // 0b1_1000 through 0b1_1111. Receipted does not change aborted precedence.
    .corrupt,
    .delete_transaction,
    .corrupt,
    .delete_transaction,
    .corrupt,
    .delete_transaction,
    .corrupt,
    .delete_transaction,
};

fn setMarker(
    allocator: std.mem.Allocator,
    transaction_dir: []const u8,
    name: []const u8,
    present: bool,
) !void {
    const path = try markerPath(allocator, transaction_dir, name);
    defer allocator.free(path);
    if (present) {
        try writeMarker(allocator, transaction_dir, name);
    } else {
        try deleteFileIfPresent(allocator, path);
    }
}

fn writeMalformedMarker(
    allocator: std.mem.Allocator,
    transaction_dir: []const u8,
    name: []const u8,
) !void {
    const path = try markerPath(allocator, transaction_dir, name);
    defer allocator.free(path);
    try zts.file_io.writeFile(allocator, path, "truncated");
}

