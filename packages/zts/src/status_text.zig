//! Canonical HTTP reason phrases used by response objects and wire output.

pub fn forCode(status: u16) []const u8 {
    return switch (status) {
        100 => "Continue",
        101 => "Switching Protocols",
        102 => "Processing",
        103 => "Early Hints",
        200 => "OK",
        201 => "Created",
        202 => "Accepted",
        203 => "Non-Authoritative Information",
        204 => "No Content",
        205 => "Reset Content",
        206 => "Partial Content",
        207 => "Multi-Status",
        208 => "Already Reported",
        226 => "IM Used",
        300 => "Multiple Choices",
        301 => "Moved Permanently",
        302 => "Found",
        303 => "See Other",
        304 => "Not Modified",
        305 => "Use Proxy",
        307 => "Temporary Redirect",
        308 => "Permanent Redirect",
        400 => "Bad Request",
        401 => "Unauthorized",
        402 => "Payment Required",
        403 => "Forbidden",
        404 => "Not Found",
        405 => "Method Not Allowed",
        406 => "Not Acceptable",
        407 => "Proxy Authentication Required",
        408 => "Request Timeout",
        409 => "Conflict",
        410 => "Gone",
        411 => "Length Required",
        412 => "Precondition Failed",
        413 => "Payload Too Large",
        414 => "URI Too Long",
        415 => "Unsupported Media Type",
        416 => "Range Not Satisfiable",
        417 => "Expectation Failed",
        421 => "Misdirected Request",
        422 => "Unprocessable Entity",
        423 => "Locked",
        424 => "Failed Dependency",
        425 => "Too Early",
        426 => "Upgrade Required",
        428 => "Precondition Required",
        429 => "Too Many Requests",
        431 => "Request Header Fields Too Large",
        451 => "Unavailable For Legal Reasons",
        500 => "Internal Server Error",
        501 => "Not Implemented",
        502 => "Bad Gateway",
        503 => "Service Unavailable",
        504 => "Gateway Timeout",
        505 => "HTTP Version Not Supported",
        506 => "Variant Also Negotiates",
        507 => "Insufficient Storage",
        508 => "Loop Detected",
        511 => "Network Authentication Required",
        599 => "Network Connect Timeout Error",
        else => "Unknown",
    };
}

test "forCode names each status code of the IANA registry that a handler can send" {
    const std = @import("std");
    const cases = [_]struct { status: u16, phrase: []const u8 }{
        .{ .status = 102, .phrase = "Processing" },
        .{ .status = 203, .phrase = "Non-Authoritative Information" },
        .{ .status = 205, .phrase = "Reset Content" },
        .{ .status = 206, .phrase = "Partial Content" },
        .{ .status = 207, .phrase = "Multi-Status" },
        .{ .status = 208, .phrase = "Already Reported" },
        .{ .status = 226, .phrase = "IM Used" },
        .{ .status = 300, .phrase = "Multiple Choices" },
        .{ .status = 303, .phrase = "See Other" },
        .{ .status = 305, .phrase = "Use Proxy" },
        .{ .status = 307, .phrase = "Temporary Redirect" },
        .{ .status = 308, .phrase = "Permanent Redirect" },
        .{ .status = 402, .phrase = "Payment Required" },
        .{ .status = 406, .phrase = "Not Acceptable" },
        .{ .status = 407, .phrase = "Proxy Authentication Required" },
        .{ .status = 409, .phrase = "Conflict" },
        .{ .status = 410, .phrase = "Gone" },
        .{ .status = 411, .phrase = "Length Required" },
        .{ .status = 412, .phrase = "Precondition Failed" },
        .{ .status = 415, .phrase = "Unsupported Media Type" },
        .{ .status = 416, .phrase = "Range Not Satisfiable" },
        .{ .status = 417, .phrase = "Expectation Failed" },
        .{ .status = 421, .phrase = "Misdirected Request" },
        .{ .status = 423, .phrase = "Locked" },
        .{ .status = 424, .phrase = "Failed Dependency" },
        .{ .status = 425, .phrase = "Too Early" },
        .{ .status = 426, .phrase = "Upgrade Required" },
        .{ .status = 428, .phrase = "Precondition Required" },
        .{ .status = 451, .phrase = "Unavailable For Legal Reasons" },
        .{ .status = 505, .phrase = "HTTP Version Not Supported" },
        .{ .status = 506, .phrase = "Variant Also Negotiates" },
        .{ .status = 507, .phrase = "Insufficient Storage" },
        .{ .status = 508, .phrase = "Loop Detected" },
        .{ .status = 511, .phrase = "Network Authentication Required" },
    };
    for (cases) |case| try std.testing.expectEqualStrings(case.phrase, forCode(case.status));
}

test "forCode names a status code with no registered phrase Unknown" {
    const std = @import("std");
    try std.testing.expectEqualStrings("Unknown", forCode(418));
    try std.testing.expectEqualStrings("Unknown", forCode(299));
}
